#!/usr/bin/env python3
"""Write native/tests/retail_char_shading_cases.inc: random pixel inputs for
ten of DC3's shipped per-pixel standard.ps permutations (five, and five of
them again with option bit 19, the character self-shadow map), and the colour the
shipped MICROCODE computes for each (ucode_emu.py executing the xenia ucode
listing; the readable models in char_models.py are not used for the expected
values, only checked against them here as a cross-check).

  python3 gen_char_shading_cases.py [--ucode DIR] [--shaders DIR] [--per-kind 12]
"""
import argparse
import os

import numpy as np

import char_models as cm

KINDS = [  # (kind id in the test, permutation key)
    (0, cm.SKIN),
    (1, cm.SKIN_NO_RIM),
    (2, cm.HAIR),
    (3, cm.PLAIN_RIM),
    (4, cm.PLAIN_DETAIL),
]
# The same with the self-shadow map (bit 19): each key in cm.SHADOWED, in the
# order of its unshadowed form's kind, then plain without rim or normal map.
SHADOW_KINDS = [
    (5, "00000320400b5037"),   # skin
    (6, "00000300400b1037"),   # skin without rim
    (7, "00000300800b1017"),   # hair
    (8, "00000320000b1037"),   # plain with rim
    (9, "00000300000b1017"),   # plain, no rim, no normal map
]
DETAIL_KINDS = {4}   # these lines also carry the normal detail texel and c106
SHADOW_MARGIN = 0.02
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..",
                   "native", "tests", "retail_char_shading_cases.inc")


def lit(x):
    """A C float literal: %.9g, with a '.0' where it would print as an integer."""
    t = "%.9g" % float(x)
    if not any(ch in t for ch in ".en"):
        t += ".0"
    return t + "f"


def f(v):
    return "{" + ", ".join(lit(x) for x in v) + "}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ucode", default=cm.DEFAULT_UCODE)
    ap.add_argument("--shaders", default=cm.DEFAULT_SHADERS)
    ap.add_argument("--per-kind", type=int, default=12)
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()
    lines = [
        "// Generated by scripts/gpu/xenos_ucode/gen_char_shading_cases.py; do not edit.",
        "// want = oC0.rgb of the shipped standard.ps microcode (emulated) for these inputs.",
        "// kind: 0 skin %s, 1 skin without rim %s, 2 hair %s, 3 plain with rim %s,"
        " 4 plain with normal detail %s;" % tuple(k for _, k in KINDS),
        "// with the self-shadow map (bit 19): 5 skin %s, 6 skin without rim %s, 7 hair %s,"
        " 8 plain with rim %s, 9 plain %s." % tuple(k for _, k in SHADOW_KINDS),
    ]
    rng = np.random.default_rng(20261114)
    rng_detail = np.random.default_rng(20261115)   # kinds 0-3 keep their inputs
    rng_shadow = np.random.default_rng(20261116)   # and kinds 0-4 theirs
    for kind, key in KINDS + SHADOW_KINDS:
        emu = cm.emulator(a.ucode, a.shaders, key)
        shadowed = key in cm.SHADOWED
        model = cm.MODELS[cm.SHADOWED.get(key, key)]
        for _ in range(a.per_kind):
            I, c, tex = cm.rnd_inputs(rng, normal_scale=(0.8, 1.2))
            if kind in DETAIL_KINDS:
                cm.rnd_detail(rng_detail, c, tex)
            sh = None
            if shadowed:
                sh = cm.rnd_shadow(rng_shadow, I, c, tex, cm.SHADOW_REG.get(key, 6),
                                   margin=SHADOW_MARGIN)
            want = emu.run(I, c, tex)["oC0"][:3]
            m = model(I, c, tex, sh=sh) if shadowed else model(I, c, tex)
            assert np.all(np.abs(m - want) <= 1e-5 * (1 + np.abs(want))), (key, m, want)
            P = I[1][:3]
            fields = [
                str(kind), f(P), f(I[2][:3]), f(I[3][:3]), f(I[4][:3]), f(I[5][:3]),
                f(tex[0]), f(tex[1]), f(tex[2]),
                f(c[0]), f(c[1]), f(c[2]), lit(c[14][0]), f(c[19]), f(c[61]),
                "{" + ", ".join(f(c[62 + i]) for i in range(3)) + "}",
                "{" + ", ".join(f(c[66 + i]) for i in range(3)) + "}",
                "{" + ", ".join(f(c[80 + i]) for i in range(6)) + "}",
                f(want),
            ]
            if kind in DETAIL_KINDS:
                fields += [f(tex[14]), f(c[106])]
            elif shadowed:
                # the shadow map's 2x2 footprint: bilinear fractions, which of
                # the four (-,-), (+,-), (-,+), (+,+) taps is lit, c107, c108
                fields += [f([0] * 4), f([0] * 4), f(tex[("w", 5)]),
                           f([1.0 if x else 0.0 for x in tex[("lit", 5)]]),
                           f(c[107]), f(c[108])]
            lines.append("{" + ", ".join(fields) + "},")
    with open(a.out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", a.out, sum(l.startswith("{") for l in lines), "cases")


if __name__ == "__main__":
    main()
