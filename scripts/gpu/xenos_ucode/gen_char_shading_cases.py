#!/usr/bin/env python3
"""Write native/tests/retail_char_shading_cases.inc: random pixel inputs for
four of DC3's shipped per-pixel standard.ps permutations, and the colour the
shipped MICROCODE computes for each (ucode_emu.py executing the xenia ucode
listing; the readable models in char_models.py are not used for the expected
values, only checked against them here as a cross-check).

  python3 gen_char_shading_cases.py [--ucode DIR] [--shaders DIR] [--per-kind 12]
"""
import argparse
import os

import numpy as np

import char_models as cm

KINDS = [  # (kind id in the test, permutation key)
    (0, cm.SKIN),
    (1, cm.SKIN_NO_RIM),
    (2, cm.HAIR),
    (3, cm.PLAIN_RIM),
]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..",
                   "native", "tests", "retail_char_shading_cases.inc")


def f(v):
    return "{" + ", ".join("%.9gf" % float(x) for x in v) + "}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ucode", default=cm.DEFAULT_UCODE)
    ap.add_argument("--shaders", default=cm.DEFAULT_SHADERS)
    ap.add_argument("--per-kind", type=int, default=12)
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()
    lines = [
        "// Generated by scripts/gpu/xenos_ucode/gen_char_shading_cases.py; do not edit.",
        "// want = oC0.rgb of the shipped standard.ps microcode (emulated) for these inputs.",
        "// kind: 0 skin %s, 1 skin without rim %s, 2 hair %s, 3 plain with rim %s." %
        tuple(k for _, k in KINDS),
    ]
    rng = np.random.default_rng(20261114)
    for kind, key in KINDS:
        emu = cm.emulator(a.ucode, a.shaders, key)
        model = cm.MODELS[key]
        for _ in range(a.per_kind):
            I, c, tex = cm.rnd_inputs(rng, normal_scale=(0.8, 1.2))
            want = emu.run(I, c, tex)["oC0"][:3]
            m = model(I, c, tex)
            assert np.all(np.abs(m - want) <= 1e-5 * (1 + np.abs(want))), (key, m, want)
            P = I[1][:3]
            fields = [
                str(kind), f(P), f(I[2][:3]), f(I[3][:3]), f(I[4][:3]), f(I[5][:3]),
                f(tex[0]), f(tex[1]), f(tex[2]),
                f(c[0]), f(c[1]), f(c[2]), "%.9gf" % c[14][0], f(c[19]), f(c[61]),
                "{" + ", ".join(f(c[62 + i]) for i in range(3)) + "}",
                "{" + ", ".join(f(c[66 + i]) for i in range(3)) + "}",
                "{" + ", ".join(f(c[80 + i]) for i in range(6)) + "}",
                f(want),
            ]
            lines.append("{" + ", ".join(fields) + "},")
    with open(a.out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", a.out, len(lines) - 3, "cases")


if __name__ == "__main__":
    main()
