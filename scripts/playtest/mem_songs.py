#!/usr/bin/env python3
"""mem_songs.py -- resident memory song over song in ONE dc3-native process,
rendering on (PLAN H-24 / H-45): N distinct Perform songs, back to song select
after each, picked by name (`highlight`), so downloadable songs can be among
them.

  mem_songs.py --out DIR [--songs a b c ...] [--norender] [--census] [--bt]
               [--gpu-counters N] [--extra-env K=V ...]

What it reads, at every song_select_screen Enter (DC3_MEM_LOG's line):
rss / heap in use / held free / live Hmx::Objects, plus -- sampled from
outside at the same moment -- the process's /dev/nvidia* mapped resident size
(H-45's driver-side growth) and the last [GPUCOUNT] line (live bind groups,
meshes, textures).  --census adds DC3_MEM_CENSUS (classes whose live count
moved).  Writes DIR/engine.log, DIR/flow.txt, DIR/mem.json and prints a table.

Like MemoryFlatSongOverSongTest (native/tests/test_dta_flow.cpp), but rendering,
more songs, DLC on (DC3_DLC=1: the dev profile mounts <data>/dlc), and outside
ctest.  DC3_FAST_TIME steps game time per frame, so a song takes ~1 min of
wall clock and memory is not a function of box load.  Muted.  Run anything
that renders under the GPU lock.
"""
import argparse
import json
import os
import re
import subprocess
import sys
import threading
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import kitdrive  # noqa: E402

# Disc songs alternating with downloadable ones (Dance Central 2 packs).
DEFAULT_SONGS = ["macarena", "milkshake", "cupidshuffle", "badromance", "iceicebaby", "toxic",
                 "12step", "partyrockanthem", "supersonic", "getlow"]

WAIT = "wait_screen {}\n"


def flow(songs):
    """three-songs.txt's route, with `highlight` instead of counted downs."""
    out = ["# generated by scripts/playtest/mem_songs.py\n",
           WAIT.format("title_screen"), "+43 wake\n+45 confirm\n",
           WAIT.format("main_screen"), "+43 wake\n+45 confirm\n",
           WAIT.format("choose_mode_screen"), "+43 wake\n+45 confirm\n"]
    for s in songs:
        out.append(WAIT.format("song_select_screen") * 7)
        out.append(f"+43 wake\n+45 highlight {s}\n+60 confirm\n")
        out.append(WAIT.format("multiuser_screen"))
        out.append("+38 wake\n+40 confirm\n+150 confirm\n+270 confirm\n")
        out.append(WAIT.format("perform_final_results_screen") * 40)
        out.append("+90 confirm\n")
        out.append(WAIT.format("perform_complete_screen"))
        out.append("+90 confirm\n")
    out.append(WAIT.format("song_select_screen") * 7)
    return "".join(out)


MEM_RE = re.compile(r"^DC3 MEM song_select_screen rss=(\d+)MB inuse=([\d.]+)MB "
                    r"heldfree=([\d.]+)MB mmap=([\d.]+)MB .*?objects=(\d+)")
CLASS_RE = re.compile(r"^DC3 MEM   class (\S+)\s+live=(-?\d+) delta=([+-]\d+)")
GPU_RE = re.compile(r"^\[GPUCOUNT\] frame=(\d+) bindGroupsLive=(\d+) .*?pipelines=(\d+) "
                    r"gpuMeshes=(\d+) gpuTextures=(\d+)")
SONG_RE = re.compile(r"highlight '(\w+)' satisfied")


def driver_mapped_mb(pid):
    """Resident MB of the process's /dev/nvidia* mappings (smaps)."""
    total, cur = 0, False
    try:
        with open(f"/proc/{pid}/smaps") as f:
            for line in f:
                if line[0] in "0123456789abcdef" and "-" in line.split()[0]:
                    cur = "/dev/nvidia" in line or "/dev/dri" in line
                elif cur and line.startswith("Rss:"):
                    total += int(line.split()[1])
    except OSError:
        return None
    return round(total / 1024, 1)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", required=True)
    ap.add_argument("--songs", nargs="+", default=DEFAULT_SONGS)
    ap.add_argument("--norender", action="store_true")
    ap.add_argument("--census", action="store_true")
    ap.add_argument("--bt", action="store_true", help="DC3_MEM_CENSUS_BT (slow)")
    ap.add_argument("--gpu-counters", type=int, default=600)
    ap.add_argument("--timeout", type=int, default=3600, help="wall clock cap, s")
    ap.add_argument("--extra-env", nargs="*", default=[])
    ap.add_argument("--binary", default=os.path.join(REPO, "native", "build", "dc3-native"))
    a = ap.parse_args(argv)
    out = os.path.abspath(a.out)
    a.binary = os.path.abspath(a.binary)
    os.makedirs(out, exist_ok=True)
    root = os.path.join(out, "home")
    kitdrive.seed_home(root)
    fp = os.path.join(out, "flow.txt")
    with open(fp, "w") as f:
        f.write(flow(a.songs))
    env = dict(os.environ)
    env.update({"MILO_HEADLESS": "1", "MILO_FATAL_FAILS": "0", "DC3_SHOW_SPLASH": "0",
                "DC3_FAST_BOOT": "1", "DC3_FAST_TIME": "1", "DC3_CONTROLLER_MODE": "forced",
                "DC3_MEM_LOG": "1", "DC3_AUDIO_GAIN": "0", "DC3_DLC": "1",
                "DC3_CACHE_DIR": os.path.join(root, "cache"),
                "DC3_SAVE_DIR": os.path.join(root, "saves"),
                "MILO_INPUT_SCRIPT": fp, "MILO_MAX_FRAMES": str(60000 * (len(a.songs) + 1)),
                "DC3_DATA": env.get("DC3_DATA", os.path.join(REPO, "orig-assets"))})
    env.pop("DC3_DLC_DIR", None)
    if a.norender:
        env["MILO_NORENDER"] = "1"
    if a.gpu_counters:
        env["MILO_GPU_COUNTERS"] = str(a.gpu_counters)
    if a.census:
        env["DC3_MEM_CENSUS"] = "1"
    if a.bt:
        env["DC3_MEM_CENSUS_BT"] = "1"
    for kv in a.extra_env:
        k, v = kv.split("=", 1)
        env[k] = v
    log = open(os.path.join(out, "engine.log"), "w")
    t0 = time.time()
    p = subprocess.Popen([a.binary], cwd=os.path.dirname(a.binary), env=env,
                         stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
                         errors="replace")
    killer = threading.Timer(a.timeout, p.kill)
    killer.start()
    samples, gpu, song, classes = [], None, None, []
    for line in p.stdout:
        log.write(line)
        m = SONG_RE.search(line)
        if m:
            song = m.group(1)
        m = GPU_RE.match(line)
        if m:
            gpu = dict(zip(("frame", "bind_groups", "pipelines", "meshes", "textures"),
                           map(int, m.groups())))
        m = CLASS_RE.match(line)
        if m and samples:
            samples[-1].setdefault("classes", {})[m.group(1)] = int(m.group(3))
        m = MEM_RE.match(line)
        if m:
            s = {"i": len(samples), "after": song if samples else None,
                 "t": round(time.time() - t0), "rss": int(m.group(1)),
                 "inuse": float(m.group(2)), "heldfree": float(m.group(3)),
                 "mmap": float(m.group(4)), "objects": int(m.group(5)),
                 "driver_mb": driver_mapped_mb(p.pid), "gpu": gpu,
                 "load": round(os.getloadavg()[0])}
            # song select is entered several times between songs only through
            # the flow's repeated waits -- one Enter per visit in practice
            samples.append(s)
            print(f"song select {s['i']:2d} after {str(s['after']):<16} rss {s['rss']:5d} MB "
                  f"inuse {s['inuse']:6.1f} heldfree {s['heldfree']:6.1f} objects {s['objects']:6d} "
                  f"driver {s['driver_mb']} MB gpu {gpu} load {s['load']}", flush=True)
    rc = p.wait()
    killer.cancel()
    log.close()
    res = {"songs": a.songs, "rc": rc, "seconds": round(time.time() - t0), "samples": samples,
           "render": not a.norender}
    with open(os.path.join(out, "mem.json"), "w") as f:
        json.dump(res, f, indent=1)
    print(f"rc {rc}, {res['seconds']} s, {len(samples)} song select samples "
          f"for {len(a.songs)} songs")
    return 0 if len(samples) == len(a.songs) + 1 else 1


if __name__ == "__main__":
    sys.exit(main())
