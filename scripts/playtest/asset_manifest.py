#!/usr/bin/env python3
"""asset_manifest.py -- what game data a PLAYER box needs, and whether it has it.

The desktop game reads its content out of the ten archives in orig-assets/gen
(main_xbox.hdr + main_xbox_0..9.ark).  From orig-assets/extracted it reads only
a handful of loose files, measured with strace over a boot and a whole song
(PLAN L-1, np-playtest-kit): the song directory list and two .dta files that
ContentMgr enumerates, and the skeleton milo.  Everything else in extracted/ is
either an unpacked copy of the archives (for tools and the web build) or
DERIVED by a generator and used only by the web build:

  sfx/gen/xma_pcm/*.pcm, *.ogg   XMA SFX decoded to PCM (scripts/web/
                                 gen_sfx_sidecars.sh, gen_sfx_ogg.py); the
                                 desktop decodes at load time and writes .pcm
                                 sidecars to <data>/sfx/gen/xma_pcm itself
  videos/*.webm                  Bink transcodes (scripts/web/transcode_bink.py);
                                 the desktop decodes the .bik in the archive
  web-video-manifest.json        index of those transcodes
  *.milo_xbox sizes              this box's extracted milos are INFLATED
                                 (extract_ark.sh --inflate) for the web build,
                                 so the same file is larger here than in a raw
                                 extraction; that is not damage

  asset_manifest.py check   [--data DIR] [--manifest FILE] [--hash]
  asset_manifest.py generate [--data DIR] [--out FILE]      (on a box known good)
  asset_manifest.py list    [--data DIR] > box.tsv           (every file + size)
  asset_manifest.py compare A.tsv B.tsv                      (what B lacks / differs)

check exit codes: 0 everything the desktop needs is there and the archives
match; 3 something required is missing (listed); 4 an archive's size (or with
--hash, sha256) differs from the manifest; 2 usage/manifest unreadable.
"""
import argparse
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
DEFAULT_MANIFEST = os.path.join(REPO, "native", "playtest", "assets-manifest.json")
ARKS = ["gen/main_xbox.hdr"] + [f"gen/main_xbox_{i}.ark" for i in range(10)]
# Loose files the desktop opens outside the archives (strace, boot + a song).
SKELETON = "extracted/(..)/(..)/system/run/ham/gen/skeleton.milo_xbox"
SONG_DTAS = ["extracted/songs/songs.dta", "extracted/songs/missing_song_data.dta"]
DERIVED = [
    ("extracted/sfx/gen/xma_pcm/", "XMA SFX decoded to PCM/ogg for the web build "
     "(scripts/web/gen_sfx_sidecars.sh); the desktop does not read them"),
    ("extracted/videos/", ".webm transcodes of the Bink movies for the web build "
     "(scripts/web/transcode_bink.py); the desktop plays the .bik from the archive"),
    ("extracted/web-video-manifest.json", "index of the web video transcodes"),
]


def default_data():
    d = os.environ.get("DC3_DATA")
    return d if d else os.path.join(REPO, "orig-assets")


def sha256(path, chunk=1 << 22):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            b = f.read(chunk)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def song_dirs(data):
    root = os.path.join(data, "extracted", "songs")
    try:
        return sorted(e for e in os.listdir(root) if os.path.isdir(os.path.join(root, e)))
    except OSError:
        return []


def generate(a):
    data = a.data
    man = {"format": "dc3-player-assets v1",
           "note": "generated by scripts/playtest/asset_manifest.py generate; see its docstring",
           "archives": [], "loose": [], "song_dirs": song_dirs(data), "extracted_summary": {}}
    for rel in ARKS:
        p = os.path.join(data, rel)
        print(f"hashing {rel} ...", file=sys.stderr)
        man["archives"].append({"path": rel, "size": os.path.getsize(p), "sha256": sha256(p)})
    for rel in SONG_DTAS + [SKELETON]:
        p = os.path.join(data, rel)
        man["loose"].append({"path": rel, "size": os.path.getsize(p), "sha256": sha256(p)})
    ext = os.path.join(data, "extracted")
    for top in sorted(os.listdir(ext)):
        n = b = 0
        for dp, _, fs in os.walk(os.path.join(ext, top)):
            for f in fs:
                n += 1
                b += os.path.getsize(os.path.join(dp, f))
        man["extracted_summary"][top] = {"files": n, "bytes": b}
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w") as f:
        json.dump(man, f, indent=1)
        f.write("\n")
    print(f"wrote {a.out}", file=sys.stderr)
    return 0


def check(a):
    try:
        with open(a.manifest) as f:
            man = json.load(f)
    except (OSError, ValueError) as e:
        print(f"cannot read the asset manifest {a.manifest}: {e}")
        return 2
    data = a.data
    missing, wrong, notes = [], [], []
    if data != data.lower():
        wrong.append(f"the game data path {data} has capital letters; the game lower-cases "
                     "file paths and cannot open it (PLAN H-16). Move or link it to a "
                     "lower-case path and set DC3_DATA")
    for e in man["archives"]:
        p = os.path.join(data, e["path"])
        if not os.path.isfile(p):
            missing.append(f"{e['path']} (game archive, {e['size'] / 1e9:.2f} GB)")
            continue
        size = os.path.getsize(p)
        if size != e["size"]:
            wrong.append(f"{e['path']} is {size} bytes, expected {e['size']} (a partial copy?)")
        elif a.hash and sha256(p) != e["sha256"]:
            wrong.append(f"{e['path']} has the right size but different contents (sha256)")
    for e in man["loose"]:
        p = os.path.join(data, e["path"])
        if not os.path.isfile(p):
            missing.append(e["path"])
        elif sha256(p) != e["sha256"]:
            wrong.append(f"{e['path']} differs from this kit's (sha256)")
    have = set(song_dirs(data))
    lack = [s for s in man["song_dirs"] if s not in have]
    if lack:
        missing.append(f"{len(lack)} of {len(man['song_dirs'])} song folders under "
                       f"extracted/songs/ (first: {', '.join(lack[:5])})")
    for prefix, why in DERIVED:
        if not os.path.exists(os.path.join(data, prefix)):
            notes.append(f"{prefix} absent: fine for the desktop ({why})")
    if missing:
        print(f"MISSING from {data}:")
        for m in missing:
            print(f"  - {m}")
    if wrong:
        print(f"WRONG in {data}:")
        for m in wrong:
            print(f"  - {m}")
    for n in notes:
        print(f"  note: {n}")
    if not missing and not wrong:
        print(f"ok: {data} has the {len(man['archives'])} archives"
              f"{' (sha256 checked)' if a.hash else ' (sizes checked; --hash for contents)'}"
              f", {len(man['loose'])} loose files and {len(man['song_dirs'])} song folders "
              "the desktop game reads")
        return 0
    return 3 if missing else 4


def list_files(a):
    root = a.data
    for dp, dns, fs in os.walk(root):
        dns.sort()
        for f in sorted(fs):
            p = os.path.join(dp, f)
            try:
                print(f"{os.path.relpath(p, root)}\t{os.path.getsize(p)}")
            except OSError:
                pass
    return 0


def compare(a):
    def load(p):
        out = {}
        with open(p) as f:
            for line in f:
                k, _, v = line.rstrip("\n").rpartition("\t")
                if k:
                    out[k] = int(v)
        return out
    A, B = load(a.a), load(a.b)
    only_a = sorted(set(A) - set(B))
    diff = sorted(k for k in set(A) & set(B) if A[k] != B[k])
    print(f"{a.a}: {len(A)} files {sum(A.values()) / 1e9:.2f} GB; "
          f"{a.b}: {len(B)} files {sum(B.values()) / 1e9:.2f} GB")
    print(f"in A, not in B: {len(only_a)} files, {sum(A[k] for k in only_a) / 1e9:.2f} GB")
    print(f"different size: {len(diff)}")
    by_top = {}
    for k in only_a:
        top = "/".join(k.split("/")[:3])
        by_top[top] = by_top.get(top, 0) + 1
    for top, n in sorted(by_top.items(), key=lambda kv: -kv[1])[:20]:
        print(f"  {n:6d}  {top}")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate")
    g.add_argument("--data", default=default_data())
    g.add_argument("--out", default=DEFAULT_MANIFEST)
    c = sub.add_parser("check")
    c.add_argument("--data", default=default_data())
    c.add_argument("--manifest", default=DEFAULT_MANIFEST)
    c.add_argument("--hash", action="store_true", help="sha256 the 6.6 GB of archives too")
    l = sub.add_parser("list")
    l.add_argument("--data", default=default_data())
    m = sub.add_parser("compare")
    m.add_argument("a")
    m.add_argument("b")
    a = ap.parse_args(argv)
    if getattr(a, "data", None):
        a.data = os.path.abspath(a.data)
    return {"generate": generate, "check": check, "list": list_files, "compare": compare}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
